package io.github.jamoamo.honeycomb.rest.auth;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Makes an endpoint public: it is invoked without authentication, and any credential the caller presents is
 * ignored.
 *
 * <p>
 * On an adapter class it applies to every endpoint that does not itself declare {@link RequiresScopes} or
 * {@link RequiresRoles}.
 * </p>
 *
 * @author James Amoore
 * @since 1.1.0
 */
@Documented
@Target({ElementType.METHOD, ElementType.TYPE})
@Retention(RetentionPolicy.RUNTIME)
public @interface PermitAll
{
}
